def detect_poem(mesras):
    """
    تشخیصِ وزنِ یک شعرِ کامل (چند بیت) — قیدی بسیار قوی‌تر از تک‌بیت.
    همهٔ مصراع‌های یک شعر هم‌وزن‌اند؛ وزنی برنده است که در *همهٔ* آن‌ها جور دربیاید.
    mesras: فهرستِ مصراع‌ها (یا رشتهٔ چندخطی)
    """
    if isinstance(mesras, str):
        mesras = [x.strip() for x in mesras.strip().splitlines() if x.strip()]
    idxs = [_by_len(scan_line(m)) for m in mesras]
    n = len(idxs)
    rows = []
    for nm, a, p, f in METERS:
        cs = [meter_cost(ix, p, nm) for ix in idxs]
        cs = [min(c, 6.0) for c in cs]          # سقف: یک مصراعِ بد کلّ را نابود نکند
        avg = sum(cs) / n
        prior = -MU * math.log10(f + 0.05)
        rows.append(dict(name=nm, ark=a, pat=p, freq=f,
                         costs=cs, summ=avg, score=avg + prior))
    rows.sort(key=lambda r: (round(r["score"], 3), -r["freq"]))
    if len(LEXICON) >= LEX_MIN:
        for r in rows[:LEX_TOPK]:
            r["lex"] = sum(lex_score(m, r["pat"], r["name"]) for m in mesras) / n
            r["score"] += r["lex"]
        rows = sorted(rows[:LEX_TOPK], key=lambda r: (round(r["score"], 3), -r["freq"])) + rows[LEX_TOPK:]
    b = rows[0]
    worst = max(b["costs"])
    if   b["summ"] < 0.5 and worst < 1.2: conf = "بسیار بالا"
    elif b["summ"] < 1.0:                 conf = "بالا"
    elif b["summ"] < 1.8:                 conf = "متوسط"
    elif b["summ"] < 3.0:                 conf = "پایین"
    else:                                 conf = "نامطمئن"
    return rows, conf


