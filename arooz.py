# ============================================================ ۱) نرمال‌سازی
_ARABIC_MAP = {'ي':'ی','ك':'ک','ﻻ':'لا','ة':'ه','ۀ':'ه','أ':'ا','إ':'ا','ٱ':'ا',
               'ى':'ی','ؤ':'و','ئ':'ی','ء':'','\u200c':' ','ـ':''}
FATHA,KASRA,DAMMA='\u064E','\u0650','\u064F'
SUKUN,SHADDA='\u0652','\u0651'
TANWIN_FATH,MADDA='\u064B','\u0653'
SHORT_VOWELS={FATHA,KASRA,DAMMA}
def normalize(t):
    t=unicodedata.normalize('NFC',t)
    t=''.join(_ARABIC_MAP.get(c,c) for c in t)
    ok=set("ابپتثجچحخدذرزژسشصضطظعغفقکگلمنوهیآ ")|SHORT_VOWELS|{SUKUN,SHADDA,TANWIN_FATH,MADDA}
    t=''.join(c if c in ok else ' ' for c in t)
    return ' '.join(t.split())

CONS=set("بپتثجچحخدذرزژسشصضطظعغفقکگلمن")
LONG=set("اوی")

# ================================================ ۲) نویسه → توکن (نماد،حرف)
# نمادها: C صامت | V مصوت بلند | v مصوت کوتاه | E هِ پایانی(کوتاه/بلند) |
#         W واو مبهم | Y یِ مبهم | A الفِ آغازین مبهم | B مرز واژه
def _units(w):
    i,n=0,len(w)
    while i<n:
        b=w[i]; i+=1; m=set()
        while i<n and unicodedata.combining(w[i]): m.add(w[i]); i+=1
        yield b,m

def tokenize_word(word):
    if word=='و': return [('Q','و')]      # واو عطف: کوتاه (وُ) یا بلند (او)
    toks=[]; U=list(_units(word)); n=len(U)
    i=0
    while i<n:
        base,marks=U[i]
        start=(i==0); last=(i==n-1)
        shadda=SHADDA in marks; sukun=SUKUN in marks
        short=marks&SHORT_VOWELS; madda=MADDA in marks
        prevb=U[i-1][0] if i>0 else ''
        nextb=U[i+1][0] if i+1<n else ''
        nxt_is_vowel = nextb in ('ا','آ','و','ی','ه')
        def cons(letter=base):
            toks.append(('C',letter))
            if shadda: toks.append(('C',letter))
            if short:  toks.append(('v',''))
        # اِی/اُو آغازین
        if start and base=='ا' and nextb in ('ی','و') and not (U[i+1][1]&SHORT_VOWELS):
            toks.append(('H','ء')); toks.append(('V',nextb)); i+=2; continue
        if base=='آ' or (base=='ا' and madda):
            toks.append(('V','ا'))
        elif base=='ا':
            toks.append((('v','') if short else ('A','ا')) if start else ('V','ا'))
        # ───── واو ─────
        elif base=='و':
            if short:              cons()                      # وَ/وِ = صامت + مصوت
            elif sukun:            toks.append(('V','و'))
            elif start:            cons()                      # واوِ آغازین = صامت (وَرنه)
            elif prevb=='خ':       toks.append(('X','و'))      # واوِ معدوله (خواب/خون/خوش)
            else:                  toks.append(('W','و'))      # مبهم (بود=بُوَد | خون=xūn)
        # ───── یا ─────
        elif base=='ی':
            if short:              cons()
            elif sukun:            toks.append(('V','ی'))
            elif start:            cons()                      # یِ آغازین = صامت (یار)
            elif prevb in CONS and not nxt_is_vowel:
                                   toks.append(('V','ی'))      # پس از صامت، پیش از صامت/پایان = مصوتِ بلندِ ī
            else:                  toks.append(('Y','ی'))      # مبهم (سیاه، رأی)
        elif base=='ه':
            if short: cons()
            elif last and n>1 and prevb!='آ':
                # هِ پایانیِ e — پس از صامت (نامه) یا پس از ی/و (مایه، سایه)
                toks.append(('E','ه'))
            else: cons()
        elif base=='ع':            toks.append(('N','ع'))      # ع: صامت یا حذف
        elif base in CONS:         cons()
        i+=1
    return toks

def _mark_shortenable(wt):
    """مصوتِ بلندِ پایانِ واژه می‌تواند کوتاه شود (اختیارِ زبانی: تغییرِ کمیّتِ مصوت)."""
    if wt and wt[-1][0]=='V':
        wt=wt[:-1]+[('S', wt[-1][1])]
    return wt

def tokenize_line(line):
    ws=line.split(); toks=[]
    for wi,w in enumerate(ws):
        if toks: toks.append(('B','B'))
        wt=_mark_shortenable(tokenize_word(w))
        toks.extend(wt)
        if wi < len(ws)-1 and wt:                # کسرهٔ اضافهٔ اختیاری (نه بعدِ واژهٔ آخر)
            last=wt[-1][0]
            toks.append(('Z','ی') if last in ('V','E','W','Y','A','Q') else ('Z','')) 
    return toks

# ==================================== ۳) گسترشِ ابهام (W/Y/A/E) → قطعی
PEN_MAX=7   # هرسِ بی‌خطر: جریمهٔ بیش از این هرگز برنده نمی‌شود (λ×7≈۲.۴)
_EXP_CACHE={}
def expand_ambiguous(toks, full=False):
    """هر خوانشِ ممکن + «جریمهٔ باورپذیری»: خوانشی که انتخاب‌های نادرتری کرده
    (کسرهٔ اضافهٔ ساختگی، حذفِ ع، واو عطفِ بلند و…) جریمهٔ بیشتری می‌گیرد."""
    OPT={'W':[(('C','و'),0),(('V','و'),0)],
         'Y':[(('C','ی'),0),(('V','ی'),0)],
         'A':[(('v',''),0),(('V','ا'),0)],
         'E':[(('v',''),0),(('V',''),1)],
         'S':[(('V','x'),0),(('v',''),1)]}   # مصوتِ بلندِ پایانی: بلند | کوتاه‌شده          # هِ پایانیِ بلند = نادر
    MULTI={'H':[([('C','ء')],0),([],0)],           # همزهٔ آغازین: هست | وصل
           'N':[([('C','ع')],0),([],1)],           # حذفِ ع = نادرتر
           'X':[([],0),([('V','و')],0)],           # واو معدوله
           'Q':[([('v','')],0),                    # ـُ چسبان: «لب و» → لَ‌بُ  (پرکاربرد)
                ([('C','و'),('v','')],0),          # وُ  : «ما و تو» → ما وُ تو
                ([('V','و')],1)],                  # او : بلند (نادر)   # واو عطفِ بلند = نادر
           'Z':[([],0),([('v','')],0)] + ([([('V','')],1)] if full else []),
           'Zy':[([],0),([('C','ی'),('v','')],0)] + ([([('C','ی'),('V','')],1)] if full else [])}
    _k=(tuple(toks), full)
    if _k in _EXP_CACHE: return _EXP_CACHE[_k]
    res=[([],0)]
    for t in toks:
        s=t[0]
        if s in('C','V','v','B'):
            res=[(r+[t],p) for r,p in res]
        elif s=='Z':
            key='Zy' if t[1]=='ی' else 'Z'
            res=[(r+o,p+q) for r,p in res for o,q in MULTI[key]]
        elif s in MULTI:
            res=[(r+o,p+q) for r,p in res for o,q in MULTI[s]]
        elif s=='S':
            res=[(r+[('V',t[1])],p) for r,p in res] + [(r+[('v','')],p+1) for r,p in res]
        else:
            res=[(r+[o],p+q) for r,p in res for o,q in OPT[s]]
        if len(res)>4000:
            res=sorted(res,key=lambda z:z[1])
            mn=res[0][1]
            res=[x for x in res if x[1]<=mn+PEN_MAX][:40000]
    res.sort(key=lambda z:z[1])
    mn=res[0][1] if res else 0
    res=[x for x in res if x[1]<=mn+PEN_MAX]
    _EXP_CACHE[_k]=res
    return res

