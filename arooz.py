def align(line, pattern, max_try=3000):
    """مصراع + وزنِ *معلوم* → [(واژه، رشتهٔ وزن), ...] یا None
       DP روی (جایگاهِ توکن، جایگاهِ الگو) — فقط مسیرهای سازگار با وزن."""
    line = normalize(line)
    if not line:
        return None
    best = None
    for ws, tp in text_variants(line):
        toks = tokenize_line(' '.join(ws))
        tried = 0
        for seq, pen0 in expand_ambiguous(toks, full=True):
            pen = pen0 + tp
            if best is not None and pen >= best[0]:
                break                                   # خروجِ زودهنگام
            tried += 1
            if tried > max_try:
                break
            r = _align_seq(seq, pattern)
            if r is not None:
                best = (pen, seq, r, ws)
                break
    if best is None:
        return None
    _, seq, path, ws = best
    d = _split_by_word(seq, path)
    return [(ws[k], v) for k, v in sorted(d.items()) if k < len(ws)]


def _align_seq(seq, pat):
    """دنبالهٔ توکنِ قطعی + الگو → فهرستِ (شروع، پایان، وزنِ هجا) یا None"""
    n, m = len(seq), len(pat)
    memo = {}

    def go(i, j):
        while i < n and seq[i][0] == 'B':
            i += 1
        if i == n:
            return [] if j >= m - 1 else None      # هجای پایانی آزاد
        if j >= m:
            return None
        key = (i, j)
        if key in memo:
            return memo[key]
        memo[key] = None
        for nuc_i, nuc, coda_start in _onsets(seq, i):
            for c in (0, 1, 2):
                end = coda_start + c
                if end > n:
                    break
                coda = []
                ok = True
                for t in range(coda_start, end):
                    if seq[t][0] != 'C':
                        ok = False
                        break
                    coda.append(seq[t][1])
                if not ok:
                    break
                for w in _weight(nuc, coda):
                    opts = [w]
                    if w == '-U' and (end == n or seq[end][0] == 'B'):
                        opts.append('-')          # تخفیفِ کشیده
                    for wt in opts:
                        L = len(wt)
                        if j + L > m:
                            continue
                        # هجای پایانی آزاد است
                        last = (j + L >= m)
                        if not last and pat[j:j+L] != wt:
                            continue
                        rest = go(end, j + L)
                        if rest is not None:
                            memo[key] = [(i, end, wt)] + rest
                            return memo[key]
        return memo[key]

    return go(0, 0)


def _onsets(seq, i):
    """گزینه‌های (آغازه، هستهٔ مصوت، جایگاهِ کدا) از موقعیتِ i"""
    n = len(seq)
    s = seq[i][0]
    if s in ('V', 'v'):                                  # هجای مصوت‌آغاز
        if i == 0 or seq[i-1][0] == 'B':
            yield i, s, i + 1
        return
    k = i + 1
    if k < n and seq[k][0] in ('V', 'v'):
        yield k, seq[k][0], k + 1
    elif k < n and seq[k][0] == 'B':                     # وصل
        m2 = k
        while m2 < n and seq[m2][0] == 'B':
            m2 += 1
        if m2 < n and seq[m2][0] in ('V', 'v'):
            yield m2, seq[m2][0], m2 + 1
    elif k < n:
        yield k, 'v', k                                  # مصوتِ کوتاهِ نانوشته


def _split_by_word(seq, path, drop_liaison=True):
    """نگاشتِ هجاها به واژه‌ها. هجایی که از مرزِ واژه می‌گذرد (وصل) هر دو واژه را
    آلوده می‌کند («برتر اندیشه» → بر‌تَ‌رَن‌دی‌شه)، پس آن واژه‌ها کنار گذاشته می‌شوند."""
    bounds = [i for i, t in enumerate(seq) if t[0] == 'B']
    def widx(pos): return sum(1 for b in bounds if b < pos)
    out = defaultdict(str); dirty = set()
    for (st, en, wt) in path:
        wi = widx(st)
        out[wi] += wt
        if widx(en - 1) != wi or any(st < b < en for b in bounds):
            dirty.add(wi); dirty.add(widx(en - 1))
    if drop_liaison:
        return {k: v for k, v in out.items() if k not in dirty}
    return dict(out)




