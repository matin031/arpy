def _marks(w):
    out=[]; i=0
    while i<len(w):
        if w[i:i+2]=='-U': out.append('–ᵕ'); i+=2      # کشیده
        elif w[i]=='-':    out.append('–');  i+=1       # بلند
        else:              out.append('ᵕ');  i+=1       # کوتاه
    return ' '.join(out)

