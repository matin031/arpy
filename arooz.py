def lex_score(line, pat, name=None):
    """چقدر خوانشِ لازم برای این وزن با پیکرهٔ کلاسیک جور است؟ (کمتر = بهتر)
    ★ باید *گونه‌های مجاز* را هم بیازماید، نه فقط الگوی پایه."""
    if not LEXICON: return 0.0
    a = None
    for v in sorted(meter_variants(pat, name), key=lambda z: abs(len(z)-len(pat))):
        try: a = align(line, v)
        except Exception: a = None
        if a: break
    if a is None: return 1.1                # نتوانست در این وزن خوانده شود
    tot_s = 0.0; n = 0
    for w, wt in a:
        c = LEXICON.get(w)
        if not c: continue
        n += 1
        N = sum(c.values()); k = c.get(wt, 0)
        tot_s += -math.log10((k + 0.2) / (N + 1.0))
    return LEX_W * (tot_s / n) if n else 0.0


# ═══════════ ادغامِ فعلِ «است» (قاعدهٔ پرکاربردِ شعر) ═══════════
# «بوده است» → «بودست» ، «رفته است» → «رفتست» ، «خوب است» → «خوبست»
# هِ پایانی پیش از «است» حذف می‌شود و یک هجا کم می‌شود.
_AST = ('است', 'ست', 'استی')
def text_variants(line):
    """گونه‌های متنیِ مصراع → [(واژه‌ها، جریمه)]
       در شعرِ کلاسیک، «است» پس از واژه ادغام می‌شود (بوده است → بودست).
       شکلِ ادغام‌نشده کم‌رایج‌تر است ⇒ جریمه می‌گیرد."""
    ws = line.split()
    has_ast = any(i > 0 and w in _AST for i, w in enumerate(ws))
    outs = [(ws, 1.0 if has_ast else 0.0)]        # اصل (ادغام‌نشده)
    for i, w in enumerate(ws):
        if i > 0 and w in _AST:
            prev = ws[i-1]
            cands = []
            if prev.endswith('ه'):        cands.append(prev[:-1] + 'ست')   # بوده است → بودست
            elif prev[-1:] in ('ا','و','ی'): cands.append(prev + 'ست')      # ما است → ماست
            else:                          cands.append(prev + 'ست')        # خوب است → خوبست
            for c in cands:
                outs.append((ws[:i-1] + [c] + ws[i+1:], 0.0))
    seen = set(); res = []
    for v, p in outs:
        s = ' '.join(v)
        if s not in seen:
            seen.add(s); res.append((v, p))
    return res


_AST_HE  = re.compile(r'(\S+?)ه\s+(?:است|ست)(?=\s|$)')      # بوده است → بودست
_AST_VOW = re.compile(r'(\S*[اویآ])\s+(?:است|ست)(?=\s|$)')   # کجا است → کجاست
def line_forms(line):
    """گونه‌های نوشتاریِ یک مصراع (ادغامِ «است» در شعر رایج است)."""
    out=[line]
    for rx in (_AST_HE, _AST_VOW):
        v=rx.sub(lambda m: m.group(1)+'ست', line)
        if v!=line and v not in out: out.append(v)
    return out

MAX_WORDS = 16      # محافظ: مصراعِ بلندتر از این، انفجارِ نمایی می‌سازد
MAX_WORDS = 14      # مصراعِ فارسی عملاً هرگز بیش از این نیست؛ فراتر = خطای متن
def scan_line(line, do_normalize=True):
    """→ {رشتهٔ تقطیع: کمینه‌جریمه}"""
    if do_normalize: line = normalize(line)
    if len(line.split()) > MAX_WORDS:      # محافظ در برابر انفجارِ حافظه
        return {}
    if not line or len(line.split()) > MAX_WORDS:
        return {}                      # خطِ نامعتبر/غیرعادی — نادیده
    out = {}
    for form in line_forms(line):
        for seq, pen in expand_ambiguous(tokenize_line(form), full=True):
            for sc, sp in scan_seq(seq).items():
                tot = pen + sp
                if sc not in out or tot < out[sc]: out[sc] = tot
    return out

