def _word_scans(word):
    """تقطیع‌های ممکنِ یک واژه (مستقل) — برای امتیازدهیِ واژه‌نامه‌ای."""
    out=set()
    for seq,_p in expand_ambiguous(tokenize_word(word)):
        out |= set(scan_seq(seq).keys())
    return out

def lexicon_bonus(line):
    """چند واژهٔ این مصراع در واژه‌نامه شناخته‌شده‌اند؟ (برای گزارش)"""
    if not LEXICON: return 0,0
    ws=line.split()
    return sum(1 for w in ws if w in LEXICON), len(ws)


