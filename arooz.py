# ═══════ واج‌آراییِ فارسی (استخراج‌شده از واژه‌نامهٔ تلفظِ تیهو) ═══════
# خوشهٔ صامتیِ پایانیِ دوتایی فقط اگر در فارسی واقعاً وجود داشته باشد مجاز است.
# مثال: «دست» (st ✓) ولی «تابد» به‌صورت tābd (bd ✗) — «بتابد» = be-tā-bad است.
_PH = {'ب':'b','پ':'p','ت':'t','ث':'s','ج':'j','چ':'C','ح':'h','خ':'x','د':'d','ذ':'z',
       'ر':'r','ز':'z','ژ':'Z','س':'s','ش':'S','ص':'s','ض':'z','ط':'t','ظ':'z','ع':'?',
       'غ':'G','ف':'f','ق':'q','ک':'k','گ':'g','ل':'l','م':'m','ن':'n','و':'v','ه':'h',
       'ی':'y','ء':'?'}
_CODA_OK = frozenset({'Sn', 'yd', 'f?', 'yx', 'zd', 'Sr', 'ld', 'fl', 'zf', 'ml', 'tn', 'rj', 'qt', 'rd', 'bk', 'kl', 'fs', 'nb', 'xm', 'mn', 'bz', 'lh', 'qd', 'fz', 't?', 'yn', 'rb', 'sm', 'hn', 'vj', 'fr', 'jm', '^n', 'qr', 'yf', 'lt', 'rx', 'tf', 'hl', 'lm', 'Sd', 'yl', 'sp', 'st', 'rt', 'lx', 'tl', 'z?', 'Sk', 'Sf', '?q', 'bh', 'qf', 'dr', 'nq', 'nc', 'nt', 'yt', 'St', 'yS', 'rC', 'ks', '?d', 'nd', 'rv', 'hs', 'sn', 'ng', 'tb', 'nS', 'km', 'xz', 'sx', 'mz', 'vl', 'qS', 'rk', 'yz', '?n', 'jr', 'rl', 'xt', 'ys', 'yb', 'lc', 'mr', 'zn', 'rz', 'lb', 'rn', 'mb', 'rS', 'jh', 'yv', 'm?', 'qs', 'nj', 'bs', 'sl', 'bl', 'rs', 'zm', 'ft', 'zb', '?m', 'bq', 'sd', 'ql', 'dl', 'xS', 'zr', 'lq', 'hr', 'nf', 'hd', 'tr', '?y', 'th', '?f', 'sr', 'bt', 'zv', 'rf', 'yr', 'Sq', 'xs', 'rm', '?r', 'lf', 'nz', 'rq', '?l', 'Sm', 'sq', 'jz', 'vr', 'ms', 'mt', 'rh', '?b', 'hm', 'rp', 'br', 'rg', 'ns', 'sk', 'nk', 'kr', 'sb'})
def _coda_penalty(cl):
    """خوشهٔ پایانیِ ناموجود در فارسی ⇒ جریمهٔ سنگین."""
    if len(cl)<2: return 0.0
    k=''.join(_PH.get(c,'?') for c in cl)
    return 0.0 if k in _CODA_OK else 3.0

def _weight(nuc,coda):
    """گزینه‌های وزنیِ یک هجا. هجای کشیده معمولاً «بلند+کوتاه» (-U) است؛
    ولی در جایگاهی که وزن «بلند» بخواهد، «-» هم مجاز است (لذا هر دو تولید می‌شوند
    اما ترتیب طوری است که ابهامِ افراطی نسازد: کشیده فقط -U مگر لازم شود)."""
    if nuc=='V':                                   # مصوتِ بلند
        if len(coda)==0: return ['-']
        if len(coda)==1 and coda[0]=='ن': return ['-']   # قاعدهٔ «ن» پس از مصوت بلند
        return ['-U']                              # CV̄C / CV̄CC → کشیده
    if len(coda)==0: return ['U']                  # مصوتِ کوتاهِ باز
    if len(coda)==1: return ['-']                  # CVC → بلند
    return ['-U']                                  # CVCC → کشیده

def scan_seq(seq):
    """→ {رشتهٔ تقطیع: جریمه}. جریمه از «تخفیفِ هجای کشیده» می‌آید."""
    n=len(seq); memo={}
    def is_v(t): return t in('V','v')
    def finish(nuc,nl,j,parse):
        out={}
        for c in (0,1,2):
            end=j+c
            if end>n: break
            cl=[]; ok=True
            for t in range(j,end):
                if seq[t][0]!='C': ok=False; break
                cl.append(seq[t][1])
            if not ok: break
            wl=_weight(nuc,cl)
            cp=_coda_penalty(cl)
            if end==n:
                # ★ قاعدهٔ قطعی: هجای پایانیِ مصراع همیشه *دقیقاً یک* هجای بلند است.
                #   کشیده در پایانِ مصراع وجود ندارد — بلند است. (قاعده، نه اختیار.)
                ws=[('-',cp)]
            else:
                ws=[(x,cp) for x in wl]
                if '-U' in wl and seq[end][0]=='B':
                    ws.append(('-',cp+1))       # تخفیفِ کشیده در وسطِ مصراع = اختیارِ شاعری
            for wt,wp in ws:
                for suf,sp in parse(end).items():
                    k=wt+suf; v=wp+sp
                    if k not in out or v<out[k]: out[k]=v
            if len(out) > 40000: return out      # سقفِ ایمنی
        return out
    def parse(i):
        while i<n and seq[i][0]=='B': i+=1
        if i==n: return {'':0}
        if i in memo: return memo[i]
        res={}
        def merge(d):
            for k,v in d.items():
                if k not in res or v<res[k]: res[k]=v
        s=seq[i][0]
        if is_v(s):                                  # هجای مصوت‌آغاز
            if i==0 or seq[i-1][0]=='B':             # فقط در آغازِ واژه
                merge(finish(s,seq[i][1],i+1,parse))
        else:
            k=i+1
            if k<n and is_v(seq[k][0]):
                merge(finish(seq[k][0],seq[k][1],k+1,parse))
            elif k<n and seq[k][0]=='B':             # صامتِ پایانِ واژه → وصل
                m=k
                while m<n and seq[m][0]=='B': m+=1
                if m<n and is_v(seq[m][0]):
                    merge(finish(seq[m][0],seq[m][1],m+1,parse))
            elif k>=n:
                pass
            else:
                merge(finish('v','',k,parse))        # مصوتِ کوتاهِ نانوشته
        memo[i]=res
        return res
    return parse(0)


