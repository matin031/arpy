def match_cost(scan,pat):
    """هزینهٔ نامتقارن:
       • هجای کوتاه در جایگاهِ بلند → اختیارِ زبانیِ «بلند تلفظ کردنِ مصوتِ کوتاه»
         (که/به/تو/دو/ز…) ⇒ نیم‌هزینه.
       • هجای بلند در جایگاهِ کوتاه → غیرمجاز ⇒ هزینهٔ کامل.
       • هجای پایانی آزاد (anceps)."""
    if len(scan)!=len(pat): return 999
    c=0.0
    for i,(a,b) in enumerate(zip(scan,pat)):
        if i==len(scan)-1: continue
        if a==b or b=='x': continue
        c += 0.5 if (a=='U' and b=='-') else 1.0
    return c

