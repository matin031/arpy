def run(show_rank=True, quiet=False):
    import arooz
    ok = 0
    fails = []
    t0 = time.time()
    for i, (m1, m2, gold) in enumerate(CORPUS, 1):
        rows, conf, *_ = arooz.detect(m1, m2)
        got = rows[0]["ark"]
        hit = (got == gold)
        ok += hit
        if hit:
            if not quiet:
                print(f"OK  {i:>2}. {conf:<10} {got}", flush=True)
        else:
            rank = next((k + 1 for k, x in enumerate(rows) if x["ark"] == gold), None)
            fails.append((i, gold, got, rank))
            if not quiet:
                print(f"BAD {i:>2}. {conf:<10} {got}", flush=True)
                if show_rank:
                    print(f"        باید: {gold}   (رتبهٔ {rank})", flush=True)
    el = time.time() - t0
    print("-" * 62)
    print(f"نتیجه: {ok}/{len(CORPUS)}  ({100*ok/len(CORPUS):.0f}%)   [{el:.0f} ثانیه]")
    if fails:
        ranks = [r for *_, r in fails if r]
        print(f"خطاها: {[i for i,*_ in fails]}")
        if ranks:
            print(f"رتبهٔ پاسخِ درست در خطاها: {sorted(ranks)}"
                  f"   (میانه={sorted(ranks)[len(ranks)//2]})")
    return ok, fails


