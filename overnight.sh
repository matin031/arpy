#!/bin/bash
# overnight.sh — آموزشِ رتبه‌بند روی نمونهٔ بزرگ، روی سیستمِ خودتان.
#
# چرا این کار مهم‌ترین کارِ باقی‌مانده است
# ────────────────────────────────────────
# پاسخِ درست در ۹۴.۲٪ مواقع میانِ ۳ نامزدِ اول است و در ۹۸.۸٪ میانِ ۱۰ تا،
# ولی رتبهٔ ۱ فقط ۸۳.۸٪ است. یعنی موتور نامزدِ درست را تقریباً همیشه *می‌سازد*
# و مسئله فقط *مرتب‌کردن* است — و مرتب‌کردن را از داده یاد می‌گیریم.
# رتبه‌بندِ فعلی روی ۱۲٬۰۰۰ بیت آموخته، در حالی که پیکره ۱٬۲۷۲٬۹۳۷ بیتِ
# برچسب‌خورده دارد. این اسکریپت همان مسیر را با دادهٔ خیلی بیشتر می‌رود.
#
#   bash overnight.sh 100000        # حدودِ ۲ تا ۵ ساعت بسته به تعدادِ هسته
#
# قابلِ قطع‌شدن است: هر تکه جدا روی دیسک نوشته می‌شود و اجرای دوباره از همان‌جا
# ادامه می‌دهد. اگر نیمه‌شب سیستم خاموش شد، دوباره همین را اجرا کنید.
#
# هیچ‌چیزی را خودکار نصب نمی‌کند — در پایان یک جدول می‌دهد و انتخاب با شماست.
set -u
cd "$(dirname "$0")"

N=${1:-100000}
CSV=${P3R_CSV:-/tmp/p3r/P3R.csv}
CHUNK=3000                        # تکهٔ کوچک = کارِ ازدست‌رفتهٔ کم هنگامِ قطع
W=${WORKERS:-$(( $(nproc 2>/dev/null || echo 4) - 1 ))}
D=${WORKDIR:-/tmp/aruz_train}
mkdir -p "$D"

[ -f "$CSV" ] || { echo "پیکره پیدا نشد: $CSV
دانلود: https://media.githubusercontent.com/media/m-shahrestani/Prosody-Recognition-in-Persian-Poetry/master/dataset/P3R.csv"; exit 1; }

echo "═══ نمونه: $N بیت | تکه: $CHUNK | پردازه: $W | پوشه: $D"

# ── ۱) استخراجِ ویژگی ─────────────────────────────────────────────────
# --spread یعنی نمونه از سرتاسرِ پیکره برداشته شود. بدونِ آن «n ردیفِ نخست»
# برداشته می‌شود و چون پیکره بر پایهٔ منبع مرتب است نمونه به‌شدت کج می‌شود
# (فاصلهٔ توزیع تا واقعیت ۳۶٪ در برابرِ ۲.۴٪). این تنها تغییری بود که
# دقت را از ۸۰٪ به ۸۴٪ برد — از هر تغییرِ دیگری مؤثرتر بود.
i=0
parts=()
while [ $((i * CHUNK)) -lt "$N" ]; do
  out="$D/f_$i.npz"
  parts+=("$out")
  if [ -s "$out" ]; then
    echo "── تکه $i از قبل هست، رد شد"
  else
    echo "── تکه $i  (بیت‌های $((i*CHUNK)) تا $(((i+1)*CHUNK)))"
    python3 train_ranker.py extract "$CSV" --n "$CHUNK" --skip $((i * CHUNK)) \
            --spread "$N" --workers "$W" --out "$out" 2>&1 | tail -2
  fi
  i=$((i + 1))
done

echo "── ادغامِ ${#parts[@]} تکه"
python3 train_ranker.py merge "${parts[@]}" --out "$D/feats.npz" 2>&1 | tail -2

# ── ۲) برازش در چند اندازه ───────────────────────────────────────────
# اندازهٔ شبکه روی دقتِ *کل* تقریباً بی‌اثر است ولی تعیین می‌کند وزن‌های
# کم‌بسامد (مثلِ رباعی) قربانی می‌شوند یا نه: با ۱۲٬۰۰۰ بیت، رباعی در
# اندازه‌های ۳۲/۶۴/۱۲۸ به‌ترتیب ۶۵.۰٪ / ۷۱.۰٪ / ۷۷.۵٪ بود. با دادهٔ بیشتر
# ممکن است اندازهٔ بهینه فرق کند، پس چند تا را می‌سنجیم.
for H in 64 128 256; do
  [ -s "$D/r_$H.json" ] && { echo "── شبکهٔ $H از قبل هست"; continue; }
  echo "── برازشِ شبکهٔ $H"
  python3 train_mlp.py "$D/feats.npz" --hidden "$H" \
          --out "$D/r_$H.json" 2>&1 | tail -4
done

# ── ۳) سنجش: دقتِ کل *و* دقتِ رباعی ──────────────────────────────────
# دو معیار، چون دقتِ کل به‌تنهایی می‌تواند نابودیِ یک دستهٔ کامل را پنهان کند —
# یک‌بار نامزدی داشتم که کل را ۴.۵ واحد بالا برد و رباعی را ۱۱.۵ واحد پایین.
echo
echo "═══ نتیجه (رتبه‌بندِ فعلی برای مقایسه) ═══"
printf '%-18s %-12s %-10s\n' "رتبه‌بند" "دقتِ کل" "رباعی"
for R in ranker.json "$D"/r_*.json; do
  [ -s "$R" ] || continue
  A=$(python3 eval_p3r.py "$CSV" --n 600 --workers "$W" --ranker "$R" 2>/dev/null \
      | grep "دقتِ کل" | grep -oP '\d+\.\d+(?=%)' | head -1)
  B=$(python3 eval_class.py "$CSV" "مفعول مفاعیل مفاعیل فعل" --rankers "$R" \
      --limit 300 --workers "$W" 2>/dev/null | grep -oP '\d+\.\d+(?=%)' | tail -1)
  printf '%-18s %-12s %-10s\n' "$(basename "$R")" "${A:-؟}%" "${B:-؟}%"
done

echo
echo "برای نصبِ یک نامزد:  cp $D/r_<اندازه>.json ranker.json"
echo "بعد حتماً تطابقِ سایت را بسنجید:  python3 parity.py --n 60"
echo "و سپس ranker.json را در lib/aruz/ سایت هم بگذارید."
